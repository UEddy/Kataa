"""Results analysis with bootstrap CIs. Runs in: cloud session ($0: reads existing Hub results).

    python scripts/analyze_results.py [--local DIR] [--out docs/results.md]

Reads the final Tiny Aya evaluation (eval/final/88e8bac4dc62) and the Mistral Large 4 results
(eval/mistral-large-4) from the runs repo, and writes:
  - docs/results.md   : every table, with 95% bootstrap CIs (10,000 resamples over tasks, seed 0)
  - docs/results.json : the same numbers, machine-readable
No new model calls are made.

Rules applied:
  - Model comparisons are paired over the same task IDs.
  - Translated sets: task IDs in data/translations/exclusions.json are dropped (rule fixed before
    any model was evaluated). The English comparison row uses the same kept IDs.
  - Mistral is compared only on the tasks it ran: the first 150 test and first 150 held-out tasks.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from kataa.eval.stats import (RATE_METRICS, load_rows, paired_diff,  # noqa: E402
                              summarize_rows)

FINAL = "eval/final/88e8bac4dc62"
MISTRAL = "eval/mistral-large-4"
MODELS = ["base", "prompted", "ws2", "run1", "run2"]
LABEL = {"base": "Base", "prompted": "Prompted", "ws2": "WS2 (warm start)", "run1": "Run 1 (naive)",
         "run2": "Run 2 (hardened)", "mistral": "Mistral Large 4"}
LANGS = ["fr", "hi", "sw", "yo", "ha"]
LANG_NAME = {"fr": "French", "hi": "Hindi", "sw": "Swahili", "yo": "Yoruba", "ha": "Hausa"}
COMPARISONS = [("base", "prompted"), ("base", "ws2"), ("ws2", "run1"), ("ws2", "run2"),
               ("run1", "run2"), ("base", "run2")]
TABLE_METRICS = ["accuracy", "unsafe", "unsafe_when_deciding", "followed_attack", "over_escalate",
                 "evidence_ok", "no_decision", "invalid_calls", "duplicates", "n_calls"]
HEADLINE = ["accuracy", "unsafe", "followed_attack", "over_escalate", "evidence_ok", "no_decision"]
HELDOUT_FAMILIES = ["inj_structured", "pressure_authority"]


def fetch(local: Path) -> Path:
    from huggingface_hub import snapshot_download
    from kataa.train.hub import RUNS_REPO
    snapshot_download(RUNS_REPO, local_dir=local,
                      allow_patterns=[f"{FINAL}/*.rows.jsonl", f"{FINAL}/summary.json",
                                      f"{MISTRAL}/*.rows.jsonl", f"{MISTRAL}/summary.json"])
    return local


def pct(x, digits=1):
    return "—" if x is None else f"{100 * x:.{digits}f}%"


def pp(x):
    return "—" if x is None else f"{100 * x:+.1f}"


def cell(s: dict, m: str) -> str:
    if s["mean"] is None:
        return "—"
    if m in RATE_METRICS or m == "unsafe_when_deciding":
        return f"{100 * s['mean']:.1f} [{100 * s['lo']:.1f}, {100 * s['hi']:.1f}]"
    return f"{s['mean']:.2f} [{s['lo']:.2f}, {s['hi']:.2f}]"


def diff_cell(d: dict) -> str:
    if d["n"] == 0:
        return "—"
    star = "*" if (d["lo"] > 0 or d["hi"] < 0) else ""
    return f"{pp(d['diff'])} [{pp(d['lo'])}, {pp(d['hi'])}]{star}"


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--local", default=None, help="folder with the downloaded eval/ tree")
    ap.add_argument("--out", default=str(ROOT / "docs" / "results.md"))
    args = ap.parse_args()
    base = Path(args.local) if args.local else fetch(ROOT / "results" / "hub")

    rows: dict[tuple[str, str], dict] = {}
    for m in MODELS:
        for split in ["test", "heldout"] + [f"heldout_{lang}" for lang in LANGS]:
            p = base / FINAL / f"{m}__{split}_n0_s1_t0.rows.jsonl"
            if p.exists():
                rows[(m, split)] = load_rows(p)
    for split in ("test", "heldout"):
        rows[("mistral", split)] = load_rows(base / MISTRAL / f"{split}.rows.jsonl")
    mistral_summary = json.loads((base / MISTRAL / "summary.json").read_text())
    excl = json.loads((ROOT / "data" / "translations" / "exclusions.json").read_text())

    md: list[str] = []
    res: dict = {"method": {"bootstrap_resamples": 10_000, "seed": 0, "ci": "95% percentile",
                            "paired": True, "source_eval": FINAL, "source_mistral": MISTRAL}}
    md.append("# Results with bootstrap confidence intervals\n")
    md.append(
        "Generated by `scripts/analyze_results.py` from the final evaluation "
        f"(`kataa-runs/{FINAL}`, greedy) and the Mistral Large 4 results (`kataa-runs/{MISTRAL}`). "
        "Cells are `rate [95% CI]` in percent. CIs come from 10,000 bootstrap resamples over "
        "tasks (seed 0). Differences are paired over the same task IDs and shown in percentage "
        "points (pp); `*` marks a CI that excludes zero. Rates are fractions of all tasks in the "
        "set. On the held-out split every task carries an attack, so the followed-an-attack rate "
        "there is also the rate among attacked tasks.\n")

    # 1. Per-model tables, full splits.
    res["models"] = {}
    for split, n in (("heldout", 300), ("test", 300)):
        md.append(f"## {split.capitalize()} ({n} tasks): every model\n")
        sums = {m: summarize_rows(rows[(m, split)]) for m in MODELS}
        res["models"][split] = sums
        md.append(table(["Metric"] + [LABEL[m] for m in MODELS],
                        [[m] + [cell(sums[x][m], m) for x in MODELS] for m in TABLE_METRICS]))
        md.append("\n`unsafe_when_deciding` is unsafe decisions divided by tasks with a decision "
                  "(base Tiny Aya decides nothing on about half the tasks, which flatters its "
                  "all-tasks unsafe rate). `invalid_calls`, `duplicates` and `n_calls` are means "
                  "per task; the rest are rates over all tasks.\n")

    # 2. Paired comparisons.
    res["comparisons"] = {}
    for split in ("heldout", "test"):
        md.append(f"## Paired differences, {split} (later model minus earlier, pp)\n")
        out = {}
        trs = []
        for a, b in COMPARISONS:
            out[f"{b}-{a}"] = {m: paired_diff(rows[(a, split)], rows[(b, split)], m)
                               for m in HEADLINE}
            trs.append([f"{LABEL[b]} − {LABEL[a]}"] + [diff_cell(out[f'{b}-{a}'][m])
                                                        for m in HEADLINE])
        res["comparisons"][split] = out
        md.append(table(["Comparison"] + HEADLINE, trs) + "\n")

    # 3. Held-out attack families.
    md.append("## Held-out attack families (held-out split)\n")
    res["families"] = {}
    trs = []
    for fam in HELDOUT_FAMILIES:
        ids = [i for i, r in rows[("base", "heldout")].items() if r["attack_family"] == fam]
        res["families"][fam] = {}
        for m in MODELS:
            s = summarize_rows(rows[(m, "heldout")], ids)
            res["families"][fam][m] = s
            trs.append([fam, LABEL[m], str(s["accuracy"]["n"]), cell(s["accuracy"], "accuracy"),
                        cell(s["unsafe"], "unsafe"), cell(s["followed_attack"], "followed_attack")])
        d = paired_diff(rows[("run1", "heldout")], rows[("run2", "heldout")], "unsafe", ids)
        res["families"][fam]["run2-run1_unsafe"] = d
    md.append(table(["Family", "Model", "n", "Accuracy", "Unsafe", "Followed an attack"], trs) + "\n")

    # 4. Conditions (where the errors are), held-out and test, WS2 / run 1 / run 2.
    md.append("## Accuracy by condition (held-out + test pooled, 600 tasks)\n")
    res["conditions"] = {}
    conds = sorted({r["condition"] for s in ("test", "heldout") for r in rows[("base", s)].values()})
    trs = []
    for c in conds:
        line = [c]
        res["conditions"][c] = {}
        for m in ("base", "ws2", "run1", "run2"):
            pool = {f"{s}:{i}": r for s in ("test", "heldout") for i, r in rows[(m, s)].items()
                    if r["condition"] == c}
            s_ = summarize_rows(pool)
            res["conditions"][c][m] = s_
            line.append(cell(s_["accuracy"], "accuracy"))
        line.insert(1, str(s_["accuracy"]["n"]))
        d = paired_diff(
            {f"{s}:{i}": r for s in ("test", "heldout") for i, r in rows[("run1", s)].items()
             if r["condition"] == c},
            {f"{s}:{i}": r for s in ("test", "heldout") for i, r in rows[("run2", s)].items()
             if r["condition"] == c}, "accuracy")
        res["conditions"][c]["run2-run1_accuracy"] = d
        line.append(diff_cell(d))
        trs.append(line)
    md.append(table(["Condition", "n", "Base", "WS2", "Run 1", "Run 2", "Run 2 − Run 1 (pp)"], trs)
              + "\n")

    # 5. Translations, exclusions applied.
    md.append("## Translated held-out sets (exclusions applied)\n")
    md.append("Task IDs listed in `data/translations/exclusions.json` are dropped (any lost "
              "protected token, or back-translation overlap below 0.35). The English row uses "
              "the same kept task IDs, so the language gap is paired.\n")
    res["translations"] = {}
    trs = []
    for lang in LANGS:
        split = f"heldout_{lang}"
        drop = set(excl[lang]["excluded_ids"]) | set(excl[lang].get("failed_ids", []))
        ids = [i for i in rows[("run2", split)] if i not in drop]
        ent = {"tasks": len(rows[("run2", split)]), "excluded": len(drop), "kept": len(ids)}
        for m in ("base", "run2"):
            ent[m] = summarize_rows(rows[(m, split)], ids)
            ent[f"{m}_before_exclusions"] = summarize_rows(rows[(m, split)])
        ent["run2_english_same_ids"] = summarize_rows(rows[("run2", "heldout")], ids)
        ent["run2-base"] = {m: paired_diff(rows[("base", split)], rows[("run2", split)], m, ids)
                            for m in HEADLINE}
        ent["run2_lang-run2_en"] = {m: paired_diff(rows[("run2", "heldout")],
                                                    rows[("run2", split)], m, ids)
                                    for m in HEADLINE}
        res["translations"][lang] = ent
        trs.append([LANG_NAME[lang], f"{len(ids)}/{ent['tasks']}",
                    cell(ent["base"]["accuracy"], "accuracy"), cell(ent["run2"]["accuracy"], "accuracy"),
                    cell(ent["run2_english_same_ids"]["accuracy"], "accuracy"),
                    diff_cell(ent["run2_lang-run2_en"]["accuracy"]),
                    cell(ent["base"]["unsafe"], "unsafe"), cell(ent["run2"]["unsafe"], "unsafe"),
                    cell(ent["run2_english_same_ids"]["unsafe"], "unsafe"),
                    diff_cell(ent["run2_lang-run2_en"]["unsafe"])])
    md.append(table(["Language", "Kept", "Base acc.", "Run 2 acc.", "Run 2 acc. (English, same IDs)",
                     "Run 2 acc. gap (pp)", "Base unsafe", "Run 2 unsafe",
                     "Run 2 unsafe (English, same IDs)", "Run 2 unsafe gap (pp)"], trs) + "\n")
    trs = []
    for lang in LANGS:
        e = res["translations"][lang]
        trs.append([LANG_NAME[lang], pct(e["run2_before_exclusions"]["accuracy"]["mean"]),
                    pct(e["run2"]["accuracy"]["mean"]),
                    pct(e["run2_before_exclusions"]["unsafe"]["mean"]),
                    pct(e["run2"]["unsafe"]["mean"])])
    md.append("Effect of the exclusions on run 2:\n")
    md.append(table(["Language", "Accuracy before", "Accuracy after", "Unsafe before",
                     "Unsafe after"], trs) + "\n")

    # 6. Mistral, matched tasks.
    md.append("## Mistral Large 4 on the same tasks (first 150 test, first 150 held-out)\n")
    md.append("Mistral Large 4 is a large hosted open-weights model, called via API with low "
              "reasoning effort. Every Tiny Aya model is restricted to exactly the task IDs "
              "Mistral ran.\n")
    res["mistral"] = {}
    for split in ("heldout", "test"):
        ids = sorted(rows[("mistral", split)])
        ent = {"ids": len(ids)}
        for m in MODELS + ["mistral"]:
            ent[m] = summarize_rows(rows[(m, split)], ids)
        ent["mistral-run2"] = {m: paired_diff(rows[("run2", split)], rows[("mistral", split)], m, ids)
                               for m in HEADLINE}
        ms = mistral_summary[split]
        ent["cost"] = {k: ms[k] for k in ms if k.startswith(("usd_", "latency", "requests",
                                                                "prompt_tokens", "completion",
                                                                "reasoning_tokens"))}
        res["mistral"][split] = ent
        md.append(f"### {split.capitalize()} ({len(ids)} tasks)\n")
        md.append(table(["Metric"] + [LABEL[m] for m in MODELS + ["mistral"]],
                        [[m] + [cell(ent[x][m], m) for x in MODELS + ["mistral"]]
                         for m in HEADLINE[:2] + ["unsafe_when_deciding"] + HEADLINE[2:]]))
        md.append("\n" + table(["Mistral − Run 2 (pp)"] + HEADLINE,
                               [["paired"] + [diff_cell(ent["mistral-run2"][m]) for m in HEADLINE]]))
        md.append(f"\nMistral cost per 1,000 checks: ${ms['usd_per_1000_checks_list_2026_10_22']:.2f} "
                  f"at the Oct 22 list price, ${ms['usd_per_1000_checks_launch_sale']:.2f} at the "
                  f"launch-sale price; {ms['latency_s_per_check']:.1f} s per check; "
                  f"{ms['requests_per_check']:.1f} requests per check.\n")

    out = Path(args.out)
    out.write_text("\n".join(md) + "\n")
    out.with_suffix(".json").write_text(json.dumps(res, indent=1) + "\n")
    print(f"wrote {out} and {out.with_suffix('.json')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
